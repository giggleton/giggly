# rear-wheel drive's 6 and 8, as R's continuous scale spaces them as doubles.
#
# ggplot2 jitters with R's random numbers, which Giggly does not reproduce, so R draws Giggly's
# own distances instead: `dx` and `dy` are how far Giggly's `geom_jitter()` moved each of mpg's
