# draws exactly as its `position_jitter()` does given the same distances (checked: the same SVG,
# byte for byte). Everything but the distances themselves is ggplot2's: where each point lands,
# the axes widened to hold them, the rest of the drawing.
#
# First checked with ggplot2 4.0.3 and vdiffr 1.0.9: every element and clip path matches, in
# order. It moves with what moves test/golden/jitter.svg, and with facet_wrap().

