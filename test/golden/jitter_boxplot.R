# own distances instead: `dx` and `dy` are how far Giggly's `geom_jitter()` moved each of mpg's
# rows, in row order, and ggplot2 moves each point by them through `position_nudge()`, which
# draws exactly as its `position_jitter()` does given the same distances (checked: the same SVG,
# byte for byte). Everything but the distances themselves is ggplot2's: where each point lands,
# the axes widened to hold them, the rest of the drawing.
#
# First checked with ggplot2 4.0.3 and vdiffr 1.0.9: every element and clip path matches, and the
# one departure is test/golden/point.R's, the x axis drawn before the y. It moves with what moves
# test/golden/boxplot.svg, and with jittering.

