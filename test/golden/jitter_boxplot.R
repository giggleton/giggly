# The plot test/golden/jitter_boxplot.svg draws, drawn by ggplot2 itself, as ggplot2's own visual
# tests draw their snapshots: the independent check on that golden whenever it changes. The suite
# never runs this; it needs R, ggplot2 and vdiffr, saved as the Docker image
# giggly-r:ggplot2-4.0.3. From the repository's root:
#
#   docker run --rm -v "$PWD/test/golden":/golden:ro giggly-r:ggplot2-4.0.3 \
#     Rscript /golden/jitter_boxplot.R > jitter_boxplot.ggplot2.svg
#
# and compare the two drawings element by element, as test/golden/point.R describes.
#
# position_jitter()'s first example from ggplot2's reference page: mpg's highway mileage by
# class, a grey box for each class and its points jittered over it, each up to 0.4 either way.
#
