# The plot test/golden/jitterdodge_boxplot.svg draws, drawn by ggplot2 itself, as ggplot2's own
# visual tests draw their snapshots: the independent check on that golden whenever it changes. The
# suite never runs this; it needs R, ggplot2 and vdiffr, saved as the Docker image
# giggly-r:ggplot2-4.0.3. From the repository's root:
#
#   docker run --rm -v "$PWD/test/golden":/golden:ro giggly-r:ggplot2-4.0.3 \
#     Rscript /golden/jitterdodge_boxplot.R > jitterdodge_boxplot.ggplot2.svg
#
# and compare the two drawings element by element, as test/golden/point.R describes.
#
# position_jitterdodge()'s example from ggplot2's reference page, on mpg: highway mileage by class,
# a box for each drive train in each class, dodged side by side, and each car's point, a circle
# with a border and a fill (`shape = 21`), dodged to its drive train's box and jittered across it.
#
# ggplot2 jitters with R's random numbers, which Giggly does not reproduce, so R draws Giggly's
# own distances instead, as test/golden/jitter_boxplot.R does: `dx` is how far Giggly's
# `position: :jitterdodge` moved each of mpg's rows from its class, in row order, its dodge and its
# jitter together, and ggplot2 moves each point by it through `position_nudge()`; Giggly moves none
# up or down, as `jitter_height:` is 0. Everything but those distances is ggplot2's: the boxes and
# their dodge, the axes, the legend, the rest of the drawing.
#
# First checked with ggplot2 4.0.3 and vdiffr 1.0.9: every element and clip path matches, and the
# one departure is test/golden/point.R's, the x axis drawn before the y. It moves with what moves
# test/golden/boxplot.svg, and with jittering and dodging.

