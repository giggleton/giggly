    end
  end

  describe "datetime_width/3" do
    test "a break every step is R's breaks_width() for every unit" do
      for {extent, step, times} <- @r_datetime_widths do
        assert {extent, step, DateBreaks.datetime_width(step, extent, :utc)} ===
                 {extent, step, times}
      end
    end

    test "a break every step is R's breaks_width() across a zone's changes of offset" do
      for {zone, extent, step, seconds} <- @r_zoned_widths do
        times = DateBreaks.datetime_width(step, extent, zoned(zone))

        assert {zone, extent, step, Enum.map(times, fn time -> DateTime.to_unix(time) / 1 end)} ===
                 {zone, extent, step, seconds}
      end
    end
  end

  describe "width/2" do
    test "a break every step is R's breaks_width() for every unit" do
      for {extent, step, dates} <- @r_widths do
        assert {extent, step, DateBreaks.width(step, extent)} === {extent, step, dates}
      end
    end

    # R's `ceiling_date()` adds a year of 365 days, so 1 January of a leap year rounds up to itself
    # and the axis's last break is its first: R's breaks_width("1 year") on 2024-01-01 alone.
    test "1 January of a leap year rounds up to itself" do
      assert DateBreaks.width([year: 1], {19_723.0, 19_723.0}) === [~D[2024-01-01]]
    end
  end

  describe "pretty/1 and label/2" do
    test "the breaks and their labels are R's for every case of prettyDate()" do
      epoch = ~D[1970-01-01]

      for {extent, days, labels} <- @r_breaks do
        {dates, format} = DateBreaks.pretty(extent)

        assert {extent, Enum.map(dates, fn date -> Date.diff(date, epoch) end),
                Enum.map(dates, fn date -> DateBreaks.label(date, format) end)} ===
                 {extent, days, labels}
      end
    end
  end
