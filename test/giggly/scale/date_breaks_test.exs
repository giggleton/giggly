  describe "pretty_datetime/1 and label/2" do
    test "the breaks and their labels are R's for every step of prettyDate()" do
      epoch = ~N[1970-01-01 00:00:00]

      for {extent, seconds, labels} <- @r_datetime_breaks do
        {times, format} = DateBreaks.pretty_datetime(extent)

        assert {extent,
                Enum.map(times, fn time -> NaiveDateTime.diff(time, epoch, :second) / 1 end),
                Enum.map(times, fn time -> DateBreaks.label(time, format) end)} ===
                 {extent, seconds, labels}
      end
    end

    test "an extent of a second or under has R's breaks inside it, labelled by their second" do
      epoch = ~N[1970-01-01 00:00:00]

      for {{low, high} = extent, seconds, labels} <- @r_short_datetime_breaks do
        {times, format} = DateBreaks.pretty_datetime(extent)

        inside =
          times
          |> Enum.map(fn time -> {NaiveDateTime.diff(time, epoch, :second) / 1, time} end)
          |> Enum.filter(fn {second, _time} -> second >= low and second <= high end)

        assert {extent, Enum.map(inside, fn {second, _time} -> second end),
                Enum.map(inside, fn {_second, time} -> DateBreaks.label(time, format) end)} ===
                 {extent, seconds, labels}
      end
    end
  end

